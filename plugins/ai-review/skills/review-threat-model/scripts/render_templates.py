#!/usr/bin/env python3
"""Render the per-subject-type threat templates and the framework-id list as markdown.

    python scripts/render_templates.py            # rewrite references/*.md
    python scripts/render_templates.py --check    # exit 1 if any file is out of date

references/threats.json, templates.json and frameworks.json are the source. The markdown
files are what a reviewer reads; never edit them by hand.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REF = Path(__file__).resolve().parents[1] / "references"
FOOTER = ("\n---\nGenerated by `scripts/render_templates.py` from `threats.json` and "
          "`templates.json`. Edit the JSON, then re-run the script.\n")
FALLBACK = {"custom_probe": "custom probe", "design_review": "design review",
            "uncovered": "uncovered"}


def _load(name: str):
    return json.loads((REF / name).read_text())


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _table(uses: list[dict], threats: dict) -> list[str]:
    lines = ["| Threat id | Threat | Why it matters here | OWASP LLM 2026 | OWASP Agentic 2026 | "
             "MITRE ATLAS | With no benchmark available |",
             "|---|---|---|---|---|---|---|"]
    for use in uses:
        t = threats[use["threat"]]
        lines.append(
            f"| `{t['id']}` | **{_cell(t['name'])}.** {_cell(t['description'])} | "
            f"{_cell(use['why'])} | {', '.join(t['owasp_llm']) or '—'} | "
            f"{', '.join(t['owasp_agentic']) or '—'} | {', '.join(t['atlas']) or '—'} | "
            f"{FALLBACK[t['fallback']]}: {_cell(t['fallback_note'])} |")
    return lines


def render_template(name: str, template: dict, threats: dict) -> str:
    lines = [f"# Threat template — {template['title']}", "",
             template["applies_to"], "",
             "Which threats a catalogued benchmark covers depends on the catalogue at the time "
             "the plan is built; `scripts/plan.py` decides that. The last column says how a "
             "threat is assessed when no available benchmark covers it. A `—` in a framework "
             "column means no id was verified for that threat, not that none exists. The "
             "verified ids and where they were checked are in "
             "[framework-ids.md](framework-ids.md).", "",
             "## Questions to ask for this subject type", ""]
    lines += [f"- {q}" for q in template["ask"]]
    if template.get("guided_review"):
        g = template["guided_review"]
        lines += ["", f"Guided review for this subject type: `{g['skill']}`. {g['note']}"]
    if template.get("core_benchmark"):
        g = template["core_benchmark"]
        lines += ["", f"Core benchmark for this subject type: `{g['skill']}`. {g['note']}"]
    if "threats" in template:
        lines += ["", "## Threats", ""] + _table(template["threats"], threats)
    else:
        for feature, uses in template["features"].items():
            lines += ["", f"## Feature: {feature}", ""] + _table(uses, threats)
        lines += ["", "## Common to every feature", ""] + _table(template["common"], threats)
    lines += ["", "## What the template does not cover", "",
              "The list is a starting point for this subject type. Threats that come from the "
              "particular deployment (its data, its users, its integrations) are added by the "
              "reviewer. The template names no controls."]
    return "\n".join(lines) + "\n" + FOOTER


def render_frameworks(fw: dict) -> str:
    lines = ["# Framework ids used by the threat templates", "",
             f"Checked on {fw['checked_on']}. An id appears in a template only if it is listed "
             "here. What was checked is that the id exists with this title in the source "
             "named. Which threat an id is attached to is this skill's own reading of the "
             "framework text, not something the frameworks publish.", ""]
    for key in ("owasp_llm", "owasp_agentic", "atlas"):
        block = fw[key]
        lines += [f"## {block['name']}" + (f" — release {block['release']}"
                                           if block.get("release") else ""), "",
                  f"Source: <{block['source']}>", "", block["how_checked"], "",
                  "| Id | Title |", "|---|---|"]
        lines += [f"| {i} | {title} |" for i, title in block["ids"].items()]
        lines.append("")
    lines += ["## Not verified", "",
              "- The full text of the OWASP Top 10 for Agentic Applications PDF.",
              "- ATLAS sub-technique ids other than those listed above.",
              "- Any mapping between the three frameworks."]
    return "\n".join(lines) + "\n" + FOOTER.replace("`threats.json` and `templates.json`",
                                                   "`frameworks.json`")


def render_all() -> dict[str, str]:
    threats = {t["id"]: t for t in _load("threats.json")["threats"]}
    templates = _load("templates.json")["templates"]
    out = {f"{name}.md": render_template(name, tpl, threats) for name, tpl in templates.items()}
    out["framework-ids.md"] = render_frameworks(_load("frameworks.json"))
    return out


def main(argv: list[str]) -> int:
    stale = []
    for name, text in render_all().items():
        path = REF / name
        if "--check" in argv:
            if not path.is_file() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f"wrote references/{name}")
    for name in stale:
        print(f"STALE references/{name}: re-run scripts/render_templates.py")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
